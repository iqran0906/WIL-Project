using FMCGEnterpriseManagementSystem.Api.DTOs;
using FMCGEnterpriseManagementSystem.Api.Filters;
using FMCGEnterpriseManagementSystem.Api.Services.Interfaces;
using FMCGEnterpriseManagementSystem.Api.Validation;
using Microsoft.AspNetCore.Mvc;

namespace FMCGEnterpriseManagementSystem.Api.Controllers
{
    /*
     * Title: Handle errors in ASP.NET Core APIs
     * Author: Microsoft
     * Date: 2024
     * Availability:
     * https://learn.microsoft.com/aspnet/core/web-api/handle-errors
     */

    [ApiController]
    [Route("api/invoices")]
    [ServiceFilter(typeof(EmailApiKeyFilter))]
    public class InvoicesController : ControllerBase
    {
        private readonly IEmailService _emailService;

        public InvoicesController(IEmailService emailService)
        {
            _emailService = emailService;
        }

        // Checks whether the supplied invoice ID is valid.
        [HttpGet("{id}/email-check")]
        public IActionResult CheckEmailEligibility(int id)
        {
            if (id <= 0)
            {
                return BadRequest(new ProblemDetails
                {
                    Title = "Invalid invoice ID",
                    Detail = "Invoice ID must be a positive number.",
                    Status = StatusCodes.Status400BadRequest
                });
            }

            // This only validates the ID format.
            // It does not verify that the invoice exists.
            return Ok(new
            {
                InvoiceId = id,
                CanEmail = true
            });
        }

        /*
         * POST: api/invoices/{id}/email
         *
         * Sends an invoice PDF generated by the MVC application.
         *
         * Reference:
         * Microsoft (2026) Controller action return types
         * in ASP.NET Core Web API.
         * https://learn.microsoft.com/en-us/aspnet/core/web-api/action-return-types
         */

        [HttpPost("{id}/email")]
        public async Task<IActionResult> EmailInvoice(
            int id,
            [FromBody] EmailRequestDto request)
        {
            // Validate the route ID.
            if (id <= 0)
            {
                return BadRequest(new ProblemDetails
                {
                    Title = "Invalid invoice ID",
                    Detail = "Invoice ID must be a positive number.",
                    Status = StatusCodes.Status400BadRequest
                });
            }

            // Validate the request.
            if (request == null)
            {
                return BadRequest(new ProblemDetails
                {
                    Title = "Invalid request",
                    Detail = "An email request is required.",
                    Status = StatusCodes.Status400BadRequest
                });
            }

            // Ensure the route ID matches the request ID.
            if (request.RecordId != id)
            {
                return BadRequest(new ProblemDetails
                {
                    Title = "Invoice ID mismatch",
                    Detail = "The invoice ID in the request does not match the URL.",
                    Status = StatusCodes.Status400BadRequest
                });
            }

            // Validate the PDF attachment.
            var attachmentError =
                EmailAttachmentValidator.Validate(request);

            if (attachmentError != null)
            {
                return BadRequest(new ProblemDetails
                {
                    Title = "Invalid PDF attachment",
                    Detail = attachmentError,
                    Status = StatusCodes.Status400BadRequest
                });
            }

            // MVC has already retrieved the invoice and generated its PDF.
            // The API does not retrieve the invoice from its own database.
            // This avoids the previous duplicate-lookup 404 error.

            var result =
                await _emailService.SendInvoiceEmailAsync(request);

            if (!result.Success)
            {
                return StatusCode(
                    StatusCodes.Status502BadGateway,
                    new ProblemDetails
                    {
                        Title = "Email delivery failed",
                        Detail = "The invoice email could not be delivered.",
                        Status = StatusCodes.Status502BadGateway
                    });
            }

            return Ok(result);
        }
    }
}