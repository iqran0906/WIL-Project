using FMCGEnterpriseManagementSystem.Api.DTOs;
using FMCGEnterpriseManagementSystem.Api.Filters;
using FMCGEnterpriseManagementSystem.Api.Services.Interfaces;
using FMCGEnterpriseManagementSystem.Api.Validation;
using Microsoft.AspNetCore.Mvc;

namespace FMCGEnterpriseManagementSystem.Api.Controllers
{
    /*
     * Title: Handle errors in ASP.NET Core APIs
     * Author: Microsoft
     * Date: 2024
     * Availability:
     * https://learn.microsoft.com/aspnet/core/web-api/handle-errors
     */

    [ApiController]
    [Route("api/payments")]
    [ServiceFilter(typeof(EmailApiKeyFilter))]
    public class PaymentsController : ControllerBase
    {
        private readonly IEmailService _emailService;

        public PaymentsController(IEmailService emailService)
        {
            _emailService = emailService;
        }

        // Checks whether the supplied payment ID is valid.
        [HttpGet("{id}/email-check")]
        public IActionResult CheckEmailEligibility(int id)
        {
            if (id <= 0)
            {
                return BadRequest(new ProblemDetails
                {
                    Title = "Invalid payment ID",
                    Detail = "Payment ID must be a positive number.",
                    Status = StatusCodes.Status400BadRequest
                });
            }

            // This only validates the ID format.
            // It does not verify that the payment exists.
            return Ok(new
            {
                PaymentId = id,
                CanEmail = true
            });
        }

        // POST: api/payments/{id}/email
        // Sends a payment PDF generated by the MVC application.
        [HttpPost("{id}/email")]
        public async Task<IActionResult> EmailPayment(
            int id,
            [FromBody] EmailRequestDto request)
        {
            // Validate the route ID.
            if (id <= 0)
            {
                return BadRequest(new ProblemDetails
                {
                    Title = "Invalid payment ID",
                    Detail = "Payment ID must be a positive number.",
                    Status = StatusCodes.Status400BadRequest
                });
            }

            // Validate the request.
            if (request == null)
            {
                return BadRequest(new ProblemDetails
                {
                    Title = "Invalid request",
                    Detail = "An email request is required.",
                    Status = StatusCodes.Status400BadRequest
                });
            }

            // Ensure the route ID matches the request ID.
            if (request.RecordId != id)
            {
                return BadRequest(new ProblemDetails
                {
                    Title = "Payment ID mismatch",
                    Detail = "The payment ID in the request does not match the URL.",
                    Status = StatusCodes.Status400BadRequest
                });
            }

            // Validate the PDF attachment.
            var attachmentError =
                EmailAttachmentValidator.Validate(request);

            if (attachmentError != null)
            {
                return BadRequest(new ProblemDetails
                {
                    Title = "Invalid PDF attachment",
                    Detail = attachmentError,
                    Status = StatusCodes.Status400BadRequest
                });
            }

            // MVC has already retrieved the payment and generated its PDF.
            // The API does not retrieve the payment from its own database.

            var result =
                await _emailService.SendPaymentEmailAsync(request);

            if (!result.Success)
            {
                return StatusCode(
                    StatusCodes.Status502BadGateway,
                    new ProblemDetails
                    {
                        Title = "Email delivery failed",
                        Detail = "The payment email could not be delivered.",
                        Status = StatusCodes.Status502BadGateway
                    });
            }

            return Ok(result);
        }
    }
}